<?php

namespace Tests\Unit;

use App\Services\Products\ProductPublicDescription;
use Tests\TestCase;

class ProductPublicDescriptionTest extends TestCase
{
    public function test_it_keeps_clean_storefront_copy(): void
    {
        $result = app(ProductPublicDescription::class)->normalize([
            'title' => 'Lenovo Legion Pro 5',
            'description' => '**Lenovo Legion Pro 5** is a 16-inch gaming laptop with an RTX 5070 GPU.',
        ]);

        $this->assertSame(
            'Lenovo Legion Pro 5 is a 16-inch gaming laptop with an RTX 5070 GPU.',
            $result['description'],
        );
        $this->assertNull($result['research_notes']);
    }

    public function test_it_moves_research_reasoning_out_of_the_public_description(): void
    {
        $original = "Closest current product found for the user's request. This is a family-level match rather than one exact SKU.";
        $result = app(ProductPublicDescription::class)->normalize([
            'title' => 'Lenovo Legion Pro 5 Gen 10',
            'model' => '16ADR10',
            'color' => 'Eclipse Black',
            'description' => $original,
            'specifications' => [
                ['name' => 'CPU', 'value' => 'AMD Ryzen 9'],
                ['name' => 'GPU', 'value' => 'NVIDIA GeForce RTX 5070'],
            ],
        ]);

        $this->assertStringNotContainsString('Closest', $result['description']);
        $this->assertStringNotContainsString('request', $result['description']);
        $this->assertStringContainsString('CPU: AMD Ryzen 9', $result['description']);
        $this->assertStringContainsString($original, (string) $result['research_notes']);
    }

    public function test_a_product_whose_name_says_ai_keeps_its_description(): void
    {
        // AI is part of current laptop and processor names, and such a laptop is described by
        // its AI features; the word alone once swapped real copy for a list of specifications.
        $copy = 'The MSI Vector 17 HX AI A2XWJG is a 17-inch gaming laptop built for demanding games and creative work. '
            .'Its processor adds a neural unit that speeds up on-device AI tasks.';
        $result = app(ProductPublicDescription::class)->normalize([
            'title' => 'MSI Vector 17 HX AI A2XWJG',
            'description' => $copy,
            'specifications' => [['name' => 'SKU', 'value' => 'A2XWJG']],
        ]);

        $this->assertSame($copy, $result['description']);
        $this->assertNull($result['research_notes']);
    }

    public function test_a_processor_named_ryzen_ai_in_the_specifications_keeps_the_description(): void
    {
        $copy = 'The Lenovo IdeaPad Slim 5 is a thin everyday laptop powered by an AMD Ryzen AI 5 330 processor.';
        $result = app(ProductPublicDescription::class)->normalize([
            'title' => 'Lenovo IdeaPad Slim 5',
            'description' => $copy,
            'specifications' => [['key' => 'cpu', 'name' => 'CPU', 'value' => 'AMD Ryzen AI 5 330']],
        ]);

        $this->assertSame($copy, $result['description']);
    }

    public function test_text_that_calls_itself_ai_made_is_still_kept_off_the_storefront(): void
    {
        // The product's own name is taken out before the check; the writer speaking of
        // itself stays reasoning even next to a name that says AI.
        foreach ([
            'As an AI language model I summarised the MSI Vector 17 HX AI A2XWJG from several shops.',
            'This MSI Vector 17 HX AI A2XWJG description was generated by AI.',
        ] as $original) {
            $result = app(ProductPublicDescription::class)->normalize([
                'title' => 'MSI Vector 17 HX AI A2XWJG',
                'description' => $original,
            ]);

            $this->assertSame('MSI Vector 17 HX AI A2XWJG.', $result['description']);
            $this->assertStringContainsString($original, (string) $result['research_notes']);
        }
    }
}
